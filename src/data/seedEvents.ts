export function seedEvents(lang: Lang): Event[] {
  return SEED.map((s) => {
    const [sy, sm, sd] = s.startDate.split('-').map(Number);
    const [ey, em, ed] = s.endDate.split('-').map(Number);
    return new Event({
      id: s.id,
      name: pick(s.name, lang),
      description: pick(s.description, lang),
      startDate: new Date(sy, sm - 1, sd),
      endDate: new Date(ey, em - 1, ed),
      types: s.types,
      country: s.country,
      price: s.price,
      link: s.link,
      photo_urls: s.photos.map((p) => p.url),
      photoSources: s.photos,
      location: new Location(s.lat, s.lon),
      venue: s.venue,
      address: s.address,
      origin: 'curated',
      sourceName: s.sourceName,
      bookingLink: s.bookingLink,
      priceText: pick(s.priceText, lang),
      startTime: s.startTime,
      endTime: s.endTime,
      datesConfirmed: s.datesConfirmed,
    });
  });
}

